"""
Brings the user's own chess characters over from ballknowledge (read only): their move rules, faces, ratings, lines,
what they notice during a game, and their recorded voice clips.
Writes site/bk_bots.js and docs/voice_bk/. Safe to re-run after ballknowledge records or changes lines:
    python3 pipelines/chess_characters.py && python3 build.py
Clips are in docs/voice_bk/ (not docs/voice/, whose script deletes files it did not make).
"""
import filecmp, json, os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BK = os.path.expanduser("~/Desktop/football-prediction-model")
OUT = os.path.join(ROOT, "docs", "voice_bk")
rd = lambda *p: open(os.path.join(*p), encoding="utf-8").read()


def between(src, start, end):
    a = src.index(start)
    return src[a:src.index(end, a)]


def line_of(src, start):
    return next(l for l in src.splitlines() if l.startswith(start))


def block(src, start):
    """a top-level declaration: from its first line to the next line that is only its closing bracket"""
    a = src.index("\n" + start) + 1
    m = re.compile(r"^(\}|\}\)\(\);|\};)$", re.M).search(src, a)
    return src[a:m.end()]


def clip_name(who, text):   # the same hash as Voice.file in site/voice.js
    h = 0x811c9dc5
    for b in f"{who}|{text}".encode():
        h = ((h ^ b) * 0x01000193) & 0xffffffff
    return f"{h:08x}.mp3"


def main():
    tpl, bots, talk = rd(BK, "site", "chess_template.html"), rd(BK, "site", "chess_bots.js"), rd(BK, "site", "chess_talk.js")
    lines_js = rd(BK, "site", "bot_lines.js")
    engine = "\n".join([
        between(tpl, "const mkSf = () => {", "const Sf = (() => {"),
        line_of(tpl, "const MATE_CP"), line_of(tpl, "const wpct"), line_of(tpl, "const lineW"),
        line_of(tpl, "function rvTurn"),
        line_of(tpl, "const VAL = { p: 100"), line_of(tpl, "function evalPos"), line_of(tpl, "function negamax"), line_of(tpl, "function engineMove"),
    ])
    faces = between(bots, "const councilLogo", "/* ---------- the move rules").replace("BOTS.forEach((b, i) => { LVL[i + 1] = b.name; LVC[i + 1] = b.id; });\n", "")
    rules = between(bots, "/* ---------- the move rules", "/* ---------- wiring into the game")
    talking = between(talk, "const TALK = (() => {", "function botWatch()")
    js = f"""/* Generated by pipelines/chess_characters.py from ballknowledge's chess page. Do not edit: edit there and re-run.
   The characters, their move rules, faces, measured ratings, lines and what they notice during a game. */
const BKBots = (() => {{
const SF17_URL = "engine/stockfish-17.1-lite-single.js", SF_URL = "https://cdn.jsdelivr.net/npm/stockfish.js@10.0.2/stockfish.js";
let SF_MODERN = location.protocol !== "file:";
{engine}
let SF1 = null; const Sf = {{ analyse: (fen, o) => (SF1 = SF1 || mkSf()).analyse(fen, o) }};   /* one engine for the moves; the talking has its own */
const oppFace = (id, mood = "calm") => (id === "council" ? councilLogo() : id === "pip" ? pipSVG(mood) : COACH_SVG[id](mood));
{faces}{rules}{lines_js}
{talking}
const smallMove = (fen) => {{ const m = engineMove(new Chess(fen), 1); return {{ from: m.from, to: m.to, promotion: m.promotion }}; }};
return {{ BOTS, ELO: BOT_ELO, face: oppFace, move: botMove, smallMove, LINES: BOT_LINES, VOICE: BOT_VOICE, TALK, ALSO: TALK_ALSO, fresh: botFresh, BV }};
}})();
"""
    assert "LVL[" not in js and "aiThink" not in js, "ballknowledge's wiring leaked in: check the markers"
    open(os.path.join(ROOT, "site", "bk_bots.js"), "w", encoding="utf-8").write(js)

    L = json.loads(re.search(r"const BOT_LINES = (\{.*\});", lines_js).group(1))   # as shown: the acting cues ([sigh]) are already stripped
    voice = json.loads(re.search(r"const BOT_VOICE = (\{.*?\});", lines_js).group(1))
    index = json.loads(rd(BK, "docs", "voice", "index.json"))
    norm = lambda t: re.sub(r"\s+", " ", t).strip()
    os.makedirs(OUT, exist_ok=True)
    want, missing = {}, {}
    for bot, kinds in L.items():
        for pool in kinds.values():
            for x in pool:
                who, text = (x[0], x[1]) if isinstance(x, list) else (bot, x)
                f = index.get(f"{voice.get(who)}|{norm(text)}")
                src = os.path.join(BK, "docs", "voice", f) if f else None
                if src and os.path.exists(src) and os.path.getsize(src) > 0:
                    want[clip_name("bk_" + who, text)] = src
                elif who in voice:
                    missing[who] = missing.get(who, 0) + 1
    copied = 0
    for name, src in want.items():
        dst = os.path.join(OUT, name)
        if not os.path.exists(dst) or not filecmp.cmp(src, dst, shallow=False):
            shutil.copyfile(src, dst)
            copied += 1
    for f in os.listdir(OUT):
        if f not in want:
            os.remove(os.path.join(OUT, f))
    size = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
    print(f"site/bk_bots.js {len(js) // 1024} KB; {len(want)} voice clips ({size // 1048576} MB, {copied} new or changed)")
    print("lines without a recording yet:", missing or "none")


main()
