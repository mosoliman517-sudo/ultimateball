"""
Brings over the lines ballknowledge has recorded with Chatterbox for the sidekicks both sites share (read only there), as
site/bk_lines.js. pipelines/make_voices.py then copies the matching clips instead of recording anything.
Run:  python3 pipelines/bk_voices.py && python3 build.py
"""
import json, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BK = os.path.expanduser("~/Desktop/football-prediction-model")
SHARED = {"boot", "rita", "bench", "rim", "clock", "sneak", "pip", "vera", "bea"}
# ballknowledge's moment -> the moment here
MAP = {"welcome": "welcome", "hit": "hit", "miss": "miss", "bighit": "bighit", "streak": "streak", "best": "best", "over": "over", "rankup": "rankup", "achieve": "achieve",
       "deep": "idle", "fact": "idle", "book": "idle", "forced": "idle", "start": "welcome", "win": "best", "great": "streak", "excellent": "hit", "brilliant_q": "bighit",
       "brilliant_r": "bighit", "brilliant_minor": "bighit", "underpromo": "bighit", "mate": "over", "draw": "over", "great_game": "best", "lesson": "idle",
       "blur": "hit_blur", "career": "hit_career", "ttt": "hit_ttt", "value": "hit_value"}

os.chdir(BK); sys.dont_write_bytecode = True; sys.path.insert(0, "src")
import voice_groups as V
index = json.load(open("docs/voice/index.json", encoding="utf-8"))
out = {}
for voice, text, char, kind in V.jobs():
    f = index.get(f"{voice}|{text}")
    if char in SHARED and kind in MAP and f and f.startswith("cb_") and "ballknowledge" not in text.lower() and len(text) < 260:
        lst = out.setdefault(char, {}).setdefault(MAP[kind], [])
        if text not in lst: lst.append(text)
js = ("/* Generated by pipelines/bk_voices.py from ballknowledge: lines it has recorded with Chatterbox. Do not edit by hand. */\n"
      "const BK_LINES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "Object.entries(BK_LINES).forEach(([k, kinds]) => { if (!MASCOTS[k]) return; const L = (MASCOT_LINES[k] = { ...(MASCOT_LINES[k] || {}) });\n"
      "  Object.entries(kinds).forEach(([kind, lines]) => { L[kind] = [...new Set([...(L[kind] || []), ...lines])]; }); MASCOTS[k].lines = L; });\n")
open(os.path.join(ROOT, "site", "bk_lines.js"), "w", encoding="utf-8").write(js)
print({k: sum(len(v) for v in d.values()) for k, d in out.items()})
